#!/usr/bin/env python3
"""Generate src/font5x7.inc.S, the font the camera-side menu draws with.

The camera's own text renderer draws one line into a rectangle the handler
hardcodes, which is no use for a menu of rows. Carrying our own font means the
payload can put a character anywhere in the OSD layer with nothing but byte
writes: no display lock, no firmware call, no present.

Glyphs are written here as art so they can be read and corrected. Each is five
columns of seven rows; the emitted byte per column has bit 0 as the top row.
Only the characters the menu actually uses are defined; anything else draws as
blank rather than as whatever happened to be next in the table.
"""
