# The payload indexes the table with (character - 0x20), so every code from
# space to 'Z' needs a slot even when it is blank.
FIRST, LAST = 0x20, ord('Z')


def columns(art):
    for x in range(5):
        value = 0
        for y in range(7):
            if art[y][x] == '1':
                value |= 1 << y
        yield value


def main():
    out = [
        '/* Generated by tools/make_font.py -- edit the art there, not here.',
        ' *',
        ' * Five columns per glyph, one byte each, bit 0 = top row. Indexed by',
        f' * (character - {FIRST:#x}); undefined characters are blank.',
        ' */',
        '.global font5x7',
        'font5x7:',
    ]
    blank = (0, 0, 0, 0, 0)
    for code in range(FIRST, LAST + 1):
        glyph = GLYPHS.get(chr(code))
        data = tuple(columns(glyph)) if glyph else blank
        name = chr(code) if glyph and chr(code) != ' ' else 'space' if code == 0x20 else '?'
        out.append('    .byte ' + ', '.join(f'0x{v:02X}' for v in data)
                   + f'    @ {name}')
    out.append('')
    out.append(f'.equ FONT_FIRST, {FIRST:#x}')
    out.append(f'.equ FONT_LAST,  {LAST:#x}')
    out.append('.equ FONT_W, 5')
    out.append('.equ FONT_H, 7')
    out.append('')
    target = pathlib.Path(__file__).resolve().parent.parent / 'src/font5x7.inc.S'
    target.write_text('\n'.join(out))
    print(f'{target}: {LAST - FIRST + 1} glyph slots')


if __name__ == '__main__':
    main()
